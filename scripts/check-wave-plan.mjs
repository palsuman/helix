#!/usr/bin/env node
// Task 1.1: CI check that regenerates the wave plan from the `_Depends on:_`
// lines in tasks.md and fails on drift, including cycle detection and a
// missing-dependency-line check.
//
// It verifies:
//   1. Every task has a `_Depends on:_` line (or is explicitly the entry
//      point, "nothing").
//   2. The dependency graph built from those lines is acyclic and every
//      referenced task ID actually exists.
//   3. The wave numbers recorded in the embedded JSON wave table are
//      consistent with a fresh longest-path computation over the graph plus
//      the release-tier gates documented next to that table.
//
// If this drifts, tasks.md's own wave table is wrong and must be
// regenerated by hand (or by a smarter follow-up tool) before merge.

import { readFileSync } from "node:fs";

const REPO_ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([a-zA-Z]):/, "$1:");
const TASKS_MD = `${REPO_ROOT}/specs/helix-platform/tasks.md`;

const text = readFileSync(TASKS_MD, "utf8");
const lines = text.split("\n");

// --- Extract task IDs (e.g. "1.1", "16.8") from checklist headers -------
const taskIdPattern = /^\s*-\s*\[[ x~-]\]\s*(\d+(?:\.\d+)?)\.?\s/;
const dependsOnPattern = /_Depends on:\s*(.+?)_/;

/** @type {Map<string, {depends: string[], hasDependsLine: boolean}>} */
const tasks = new Map();
let currentTaskId = null;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const idMatch = line.match(taskIdPattern);
  if (idMatch) {
    // Only track leaf/sub tasks that have a numeric "N.M" id (phase headers
    // like "1. Phase 1" match too because \d+(?:\.\d+)? allows bare "1";
    // filter those out — phase headers don't carry _Depends on:_ lines).
    const id = idMatch[1];
    if (id.includes(".")) {
      currentTaskId = id;
      tasks.set(id, { depends: [], hasDependsLine: false });
    } else {
      currentTaskId = null;
    }
    continue;
  }
  const depMatch = line.match(dependsOnPattern);
  if (depMatch && currentTaskId) {
    const raw = depMatch[1].trim();
    const entry = tasks.get(currentTaskId);
    entry.hasDependsLine = true;
    if (/^nothing/i.test(raw)) {
      entry.depends = [];
    } else {
      // Extract task-id-shaped tokens (e.g. "1.2", "3.4, 5.6")
      const ids = raw.match(/\d+\.\d+/g) || [];
      entry.depends = ids;
    }
  }
}

// --- Validation 1: every task has a _Depends on:_ line -------------------
const missingDependsLine = [];
for (const [id, entry] of tasks) {
  if (!entry.hasDependsLine) missingDependsLine.push(id);
}

// --- Validation 2: every referenced dependency id exists ------------------
const missingDependencyTargets = [];
for (const [id, entry] of tasks) {
  for (const dep of entry.depends) {
    if (!tasks.has(dep)) {
      missingDependencyTargets.push(`${id} depends on undefined task ${dep}`);
    }
  }
}

// --- Validation 3: cycle detection (DFS with recursion stack) -------------
const cycles = [];
const WHITE = 0,
  GRAY = 1,
  BLACK = 2;
const color = new Map([...tasks.keys()].map((id) => [id, WHITE]));
const stack = [];

function visit(id) {
  color.set(id, GRAY);
  stack.push(id);
  const entry = tasks.get(id);
  if (entry) {
    for (const dep of entry.depends) {
      if (!tasks.has(dep)) continue; // already reported above
      if (color.get(dep) === GRAY) {
        const cycleStart = stack.indexOf(dep);
        cycles.push([...stack.slice(cycleStart), dep].join(" -> "));
      } else if (color.get(dep) === WHITE) {
        visit(dep);
      }
    }
  }
  stack.pop();
  color.set(id, BLACK);
}

for (const id of tasks.keys()) {
  if (color.get(id) === WHITE) visit(id);
}

// --- Validation 4: embedded wave plan matches the dependency graph --------
const wavePlanMatch = text.match(/```json\n(\{\n  "generatedFrom"[\s\S]*?\n\})\n```/);
let wavePlan = null;
let wavePlanParseError = null;
if (!wavePlanMatch) {
  wavePlanParseError = "Embedded wave-plan JSON block was not found.";
} else {
  try {
    wavePlan = JSON.parse(wavePlanMatch[1]);
  } catch (error) {
    wavePlanParseError = `Embedded wave-plan JSON is invalid: ${error.message}`;
  }
}

function minimumWave(id) {
  const phase = Number(id.split(".")[0]);
  if (phase === 17) return 22;
  if (phase === 16 || ["12.5", "12.6", "12.7", "12.8"].includes(id)) return 15;
  if (phase >= 10 && phase <= 15) return 12;
  return 1;
}

const waveMemo = new Map();
function computeWave(id) {
  if (waveMemo.has(id)) return waveMemo.get(id);
  const entry = tasks.get(id);
  const dependencyWave =
    !entry || entry.depends.length === 0
      ? 1
      : 1 + Math.max(...entry.depends.filter((dep) => tasks.has(dep)).map(computeWave));
  const w = Math.max(minimumWave(id), dependencyWave);
  waveMemo.set(id, w);
  return w;
}

let waveComputeFailed = false;
if (cycles.length === 0) {
  for (const id of tasks.keys()) {
    try {
      computeWave(id);
    } catch {
      waveComputeFailed = true;
    }
  }
}

const duplicatePlanTasks = [];
const missingPlanTasks = [];
const unknownPlanTasks = [];
const waveMismatches = [];
const continuousWaveMismatches = [];

if (wavePlan && cycles.length === 0 && !waveComputeFailed) {
  const recordedWaves = new Map();
  for (const wave of wavePlan.waves || []) {
    for (const id of wave.tasks || []) {
      if (recordedWaves.has(id)) duplicatePlanTasks.push(id);
      recordedWaves.set(id, wave.wave);
    }
  }

  const continuousWaves = new Map();
  for (const entry of wavePlan.continuous || []) {
    if (continuousWaves.has(entry.task)) duplicatePlanTasks.push(entry.task);
    continuousWaves.set(entry.task, entry.earliestWave);
  }

  for (const id of tasks.keys()) {
    const isContinuous = id.startsWith("18.");
    const recorded = isContinuous ? continuousWaves.get(id) : recordedWaves.get(id);
    if (recorded === undefined) {
      missingPlanTasks.push(id);
    } else if (recorded !== computeWave(id)) {
      const mismatch = `${id}: recorded ${recorded}, derived ${computeWave(id)}`;
      if (isContinuous) continuousWaveMismatches.push(mismatch);
      else waveMismatches.push(mismatch);
    }
  }

  for (const id of recordedWaves.keys()) {
    if (!tasks.has(id) || id.startsWith("18.")) unknownPlanTasks.push(id);
  }
  for (const id of continuousWaves.keys()) {
    if (!tasks.has(id) || !id.startsWith("18.")) unknownPlanTasks.push(id);
  }
}

// --- Report ----------------------------------------------------------------
let ok = true;

if (missingDependsLine.length > 0) {
  ok = false;
  console.error(`Tasks missing a "_Depends on:_" line: ${missingDependsLine.join(", ")}`);
}

if (missingDependencyTargets.length > 0) {
  ok = false;
  console.error("Dependencies referencing undefined tasks:");
  for (const m of missingDependencyTargets) console.error(`  - ${m}`);
}

if (cycles.length > 0) {
  ok = false;
  console.error("Cycle(s) detected in the task dependency graph:");
  for (const c of cycles) console.error(`  - ${c}`);
}

if (wavePlanParseError) {
  ok = false;
  console.error(wavePlanParseError);
}

if (waveComputeFailed) {
  ok = false;
  console.error("Wave computation failed.");
}

if (duplicatePlanTasks.length > 0) {
  ok = false;
  console.error(`Tasks duplicated in the wave plan: ${duplicatePlanTasks.join(", ")}`);
}

if (missingPlanTasks.length > 0) {
  ok = false;
  console.error(`Tasks missing from the wave plan: ${missingPlanTasks.join(", ")}`);
}

if (unknownPlanTasks.length > 0) {
  ok = false;
  console.error(`Unknown or misplaced tasks in the wave plan: ${unknownPlanTasks.join(", ")}`);
}

if (waveMismatches.length > 0) {
  ok = false;
  console.error("Scheduled task wave mismatches:");
  for (const mismatch of waveMismatches) console.error(`  - ${mismatch}`);
}

if (continuousWaveMismatches.length > 0) {
  ok = false;
  console.error("Continuous task earliest-wave mismatches:");
  for (const mismatch of continuousWaveMismatches) console.error(`  - ${mismatch}`);
}

if (!ok) {
  process.exit(1);
}

console.log(
  `Wave plan check passed: ${tasks.size} tasks, no missing dependency lines, missing targets, cycles, or embedded plan drift (computed max wave = ${Math.max(...waveMemo.values())}).`
);
